// ---------------------------------------------------------------------------
// Release signing. Secrets are NEVER stored in the source tree.
// They are read (in this order) from:
//   1. environment variables DROIDVM_KEYSTORE / DROIDVM_STORE_PASSWORD /
//      DROIDVM_KEY_ALIAS / DROIDVM_KEY_PASSWORD
//   2. <project root>/keystore.properties (git-ignored, see keystore.properties.example)
// If nothing is configured the release APK is produced unsigned.
// ---------------------------------------------------------------------------
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProps.getProperty(prop)?.takeIf { it.isNotBlank() }

